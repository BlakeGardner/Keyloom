//! Translation layer from Keyloom's internal mapping model to a valid
//! xremap configuration file.
//!
//! The rule model in [`crate::ui::model`] is the source of truth; the
//! YAML written to the user's config directory is generated output.
//! Generation is deterministic: identical mappings always produce
//! byte-identical YAML, with sources sorted by their xremap key name.
//!
//! Mappings become `modmap` entries, one block per scope (an
//! application scope, a keyboard, both, or neither), most specific
//! first. Layers become `keymap` rules guarded by a virtual modifier
//! that stands in for the held layer key (see [`LAYER_MODIFIERS`]), and
//! shortcut groups become `keymap` rules of their own.

use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use evdev::KeyCode;

use crate::ui::model::{self, AppScope, Chord, Group, Layer, Mapping, Maps, ModifierSide};

/// First line of every file Keyloom generates. Files that don't start
/// with this marker are treated as foreign and never silently replaced.
const MARKER: &str = "# Generated by Keyloom. Do not edit by hand; Keyloom overwrites this file.";

/// Stand-ins for held layer keys. xremap treats a key listed under
/// `virtual_modifiers` as a modifier for `keymap` rules and never sends
/// it on, so each layer's key is remapped to one of these and the
/// layer's rules match on it. Braille-dot codes are used because no
/// keyboard emits them: nothing but the layer key can activate a layer.
/// The pool caps how many layers a profile can generate rules for.
const LAYER_MODIFIERS: [&str; 10] = [
    "KEY_BRL_DOT1",
    "KEY_BRL_DOT2",
    "KEY_BRL_DOT3",
    "KEY_BRL_DOT4",
    "KEY_BRL_DOT5",
    "KEY_BRL_DOT6",
    "KEY_BRL_DOT7",
    "KEY_BRL_DOT8",
    "KEY_BRL_DOT9",
    "KEY_BRL_DOT10",
];

/// How many layers one profile can generate rules for.
pub const MAX_LAYERS: usize = LAYER_MODIFIERS.len();

/// Whether a deck key is one of the physical modifiers (Shift, Control,
/// Alt, Super). xremap always passes those through, so they cannot take
/// on a job inside a layer.
pub fn is_modifier_key(code: &str) -> bool {
    const MODIFIERS: [KeyCode; 8] = [
        KeyCode::KEY_LEFTSHIFT,
        KeyCode::KEY_RIGHTSHIFT,
        KeyCode::KEY_LEFTCTRL,
        KeyCode::KEY_RIGHTCTRL,
        KeyCode::KEY_LEFTALT,
        KeyCode::KEY_RIGHTALT,
        KeyCode::KEY_LEFTMETA,
        KeyCode::KEY_RIGHTMETA,
    ];
    model::key(code).is_some_and(|cap| MODIFIERS.contains(&KeyCode(cap.evdev)))
}

/// xremap key name (`KEY_*`) for a physical key on the deck, derived
/// from its evdev scancode.
pub fn key_symbol(code: &str) -> Option<String> {
    model::key(code).and_then(|cap| evdev_name(cap.evdev))
}

/// xremap key name (`KEY_*`) for an action from the editor's catalog
/// (e.g. `Escape`, `Right Control`, `Play/Pause`).
///
/// Returns `None` for actions with no evdev key, such as `Hyper` and
/// `Disabled` (the generator handles `Disabled` itself).
pub fn action_symbol(action: &str) -> Option<String> {
    // Actions named after a physical key ("Caps Lock", "Right Control",
    // "Numpad 7", "ISO Backslash", …) resolve through its scancode.
    if let Some(cap) = model::registry().find(|cap| model::key_name(cap.code) == action) {
        return evdev_name(cap.evdev);
    }
    // Older generic names still accepted from stored mappings.
    const ACTIONS: &[(&str, &str)] = &[
        ("Control", "KEY_LEFTCTRL"),
        ("Shift", "KEY_LEFTSHIFT"),
        ("Alt", "KEY_LEFTALT"),
        ("Super", "KEY_LEFTMETA"),
        ("Left", "KEY_LEFT"),
        ("Right", "KEY_RIGHT"),
        ("Up", "KEY_UP"),
        ("Down", "KEY_DOWN"),
        ("Bracket Left", "KEY_LEFTBRACE"),
        ("Bracket Right", "KEY_RIGHTBRACE"),
    ];
    ACTIONS
        .iter()
        .find(|(name, _)| *name == action)
        .map(|(_, symbol)| (*symbol).to_owned())
}

/// Canonical evdev name for a scancode (`KEY_CAPSLOCK`), which xremap
/// accepts directly. `None` for codes evdev has no name for.
fn evdev_name(scancode: u16) -> Option<String> {
    let name = format!("{:?}", KeyCode(scancode));
    name.starts_with("KEY_").then_some(name)
}

/// Everything of one profile the generator reads.
#[derive(Clone, Copy, Debug)]
pub struct Rules<'a> {
    pub maps: &'a Maps,
    pub layers: &'a [Layer],
    pub apps: &'a [AppScope],
    pub groups: &'a [Group],
}

/// An application scope as a block filter: the scope's name and id,
/// and every application id xremap should match.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct AppAxis {
    name: String,
    id: String,
    matchers: Vec<String>,
}

/// A keyboard as a block filter: xremap matches on the resolved name.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct DeviceAxis {
    name: String,
    id: String,
}

/// Where a block applies: an application scope or every application,
/// and one keyboard or every keyboard.
///
/// Scopes order most specific first (see [`model::scope_rank`]), which
/// is the order blocks are written in: xremap uses the first block that
/// mentions a key and whose filters match, so an application's block
/// has to come before a keyboard's, and both before the general one.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Scope {
    rank: u8,
    app: Option<AppAxis>,
    device: Option<DeviceAxis>,
}

impl Scope {
    fn new(app: Option<AppAxis>, device: Option<DeviceAxis>) -> Self {
        Self {
            rank: model::scope_rank(device.is_none(), app.is_none()),
            app,
            device,
        }
    }

    /// Every keyboard in every application.
    fn general() -> Self {
        Self::new(None, None)
    }

    /// Where both scopes apply, or `None` when they never overlap.
    fn intersect(&self, other: &Self) -> Option<Self> {
        fn axis<T: Clone + PartialEq>(a: &Option<T>, b: &Option<T>) -> Option<Option<T>> {
            match (a, b) {
                (None, either) | (either, None) => Some(either.clone()),
                (Some(a), Some(b)) => (a == b).then(|| Some(a.clone())),
            }
        }
        Some(Self::new(
            axis(&self.app, &other.app)?,
            axis(&self.device, &other.device)?,
        ))
    }

    /// The scope's places, for block titles:
    /// ` (COSMIC Terminal, Keychron K2 Pro)`.
    fn suffix(&self) -> String {
        let names: Vec<&str> = self
            .app
            .iter()
            .map(|app| app.name.as_str())
            .chain(self.device.iter().map(|device| device.name.as_str()))
            .collect();
        if names.is_empty() {
            String::new()
        } else {
            format!(" ({})", names.join(", "))
        }
    }

    /// The block's `application` and `device` filters.
    fn filters(&self) -> String {
        let mut filters = String::new();
        if let Some(app) = &self.app {
            let ids: Vec<String> = app.matchers.iter().map(|id| quote(id)).collect();
            filters.push_str(&format!(
                "    application:\n      only: [{}]\n",
                ids.join(", ")
            ));
        }
        if let Some(device) = &self.device {
            filters.push_str(&format!(
                "    device:\n      only: [{}]\n",
                quote(&device.name)
            ));
        }
        filters
    }
}

/// Resolves the scope ids stored with mappings, jobs, and groups.
struct Places<'a, F> {
    apps: &'a [AppScope],
    device_name: F,
}

impl<F: Fn(&str) -> String> Places<'_, F> {
    /// The scope for a device id and an application scope id, or
    /// `None` when nothing can apply there: the application scope no
    /// longer exists, or it has no applications.
    fn scope(&self, device: &str, app: &str) -> Option<Scope> {
        let app = if app.is_empty() {
            None
        } else {
            let scope = self.apps.iter().find(|scope| scope.id == app)?;
            let matchers: Vec<String> = scope.matchers().into_iter().map(str::to_owned).collect();
            if matchers.is_empty() {
                return None;
            }
            Some(AppAxis {
                name: scope.name.clone(),
                id: scope.id.clone(),
                matchers,
            })
        };
        let device = (!model::every_device(device)).then(|| DeviceAxis {
            name: (self.device_name)(device),
            id: device.to_owned(),
        });
        Some(Scope::new(app, device))
    }
}

/// What a source key produces in the generated modmap.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Output {
    /// Simple remap to one key.
    Key(String),
    /// Key emits nothing (`Disabled` in the editor).
    Disabled,
    /// Tap/hold multi-purpose key. `None` slots emit nothing.
    TapHold {
        alone: Option<String>,
        held: Option<String>,
    },
}

/// What a mapping slot turns into: `Some(None)` disables it,
/// `Some(Some(_))` remaps it, and `None` leaves it alone because it is
/// unset or holds an untranslatable action (e.g. `Hyper`).
fn slot(action: Option<&str>) -> Option<Option<String>> {
    match action {
        Some("Disabled") => Some(None),
        Some(action) => action_symbol(action).map(Some),
        None => None,
    }
}

/// Resolve one mapping into `(source symbol, output)`, or `None` when
/// nothing about it can be expressed as an xremap rule.
///
/// A "normal here" mapping maps the key to itself: listed ahead of the
/// more general blocks, that keeps the key as it is in its scope, and
/// keeps a layer the key holds from activating there.
///
/// A key that holds a layer produces the layer's modifier while held:
/// its tap action keeps working through a tap/hold key, and any hold
/// action is superseded by the layer.
fn resolve(
    code: &str,
    mapping: &Mapping,
    layer_modifier: Option<&str>,
) -> Option<(String, Output)> {
    let source = key_symbol(code)?;
    if mapping.normal {
        return Some((source.clone(), Output::Key(source)));
    }
    let tap = slot(mapping.tap.as_deref());
    let output = if let Some(modifier) = layer_modifier {
        match tap {
            Some(Some(key)) => Output::TapHold {
                alone: Some(key),
                held: Some(modifier.to_owned()),
            },
            _ => Output::Key(modifier.to_owned()),
        }
    } else {
        match slot(mapping.hold.as_deref()) {
            Some(held) => Output::TapHold {
                // Tapping falls back to the key's own behavior when only
                // a hold action is configured (xremap requires `alone`).
                alone: tap.unwrap_or(Some(source.clone())),
                held,
            },
            None => match tap {
                Some(None) => Output::Disabled,
                Some(Some(key)) => Output::Key(key),
                None => return None,
            },
        }
    };
    Some((source, output))
}

/// Layer key code → the modifier standing in for it.
type Triggers<'a> = HashMap<&'a str, &'static str>;

/// Entries for one scope, sorted by source symbol.
fn scope_entries(mappings: &[&(String, Mapping)], triggers: &Triggers) -> BTreeMap<String, Output> {
    let mut entries = BTreeMap::new();
    // Explicit mappings first; the model keeps one mapping per key and
    // scope.
    for (code, mapping) in mappings {
        let modifier = triggers.get(code.as_str()).copied();
        if let Some((source, output)) = resolve(code, mapping, modifier) {
            entries.entry(source).or_insert(output);
        }
    }
    // Two-way swaps add the reverse entry unless the reverse source
    // already has an explicit mapping.
    for (code, mapping) in mappings {
        if !mapping.swap || mapping.hold.is_some() || mapping.normal {
            continue;
        }
        let (Some(source), Some(tap)) = (key_symbol(code), mapping.tap.as_deref()) else {
            continue;
        };
        if let Some(reverse) = action_symbol(tap)
            && reverse != source
        {
            entries.entry(reverse).or_insert(Output::Key(source));
        }
    }
    entries
}

/// Single-quote a YAML scalar (device names may contain anything).
fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// The `name:` line of a block, plus its filters for a specific
/// application scope or keyboard.
fn block_header(title: &str, scope: &Scope) -> String {
    format!(
        "  - name: {}\n{}",
        quote(&format!("{title}{}", scope.suffix())),
        scope.filters()
    )
}

/// One `modmap` block.
fn modmap_block(scope: &Scope, entries: &BTreeMap<String, Output>) -> String {
    let mut block = block_header("Keyloom mappings", scope);
    block.push_str("    remap:\n");
    for (source, output) in entries {
        match output {
            Output::Key(key) => block.push_str(&format!("      {source}: {key}\n")),
            Output::Disabled => block.push_str(&format!("      {source}: []\n")),
            Output::TapHold { alone, held } => {
                let slot = |slot: &Option<String>| slot.clone().unwrap_or_else(|| "[]".to_owned());
                block.push_str(&format!("      {source}:\n"));
                block.push_str(&format!("        held: {}\n", slot(held)));
                block.push_str(&format!("        alone: {}\n", slot(alone)));
            }
        }
    }
    block
}

/// A layer whose key is a known deck key, with the modifier standing
/// in for it.
struct ResolvedLayer<'a> {
    layer: &'a Layer,
    /// The layer key's own symbol.
    trigger: String,
    modifier: &'static str,
}

/// Layers that can generate rules, in profile order. Layers whose key
/// is unset or unknown, and layers beyond the modifier pool, are left
/// out.
fn resolve_layers(layers: &[Layer]) -> Vec<ResolvedLayer<'_>> {
    layers
        .iter()
        .filter_map(|layer| key_symbol(&layer.trigger).map(|trigger| (layer, trigger)))
        .zip(LAYER_MODIFIERS)
        .map(|((layer, trigger), modifier)| ResolvedLayer {
            layer,
            trigger,
            modifier,
        })
        .collect()
}

/// The symbol a key arrives at the rules as once its mapping ran:
/// `None` when the tap is disabled and the key never arrives. A
/// hold-only, untranslatable, or "normal here" mapping leaves the key
/// as itself.
fn arrives_as(source: &str, mapping: &Mapping) -> Option<String> {
    if mapping.normal {
        return Some(source.to_owned());
    }
    match slot(mapping.tap.as_deref()) {
        Some(None) => None,
        Some(Some(key)) => Some(key),
        None => Some(source.to_owned()),
    }
}

/// The symbol a job's key arrives at the rules with, in the job's scope
/// and in every narrower scope where a mapping changes it. Mappings run
/// first, so a job on a remapped key has to match what the key became:
/// the most specific mapping covering the whole job scope sets the base
/// rule, and a mapping overlapping only part of it (the key remapped on
/// one keyboard, or in one application) adds a rule for that part. A
/// symbol of `None` means the key never arrives there.
fn rule_sources<F: Fn(&str) -> String>(
    code: &str,
    job: &Scope,
    maps: &Maps,
    places: &Places<'_, F>,
) -> Vec<(Scope, Option<String>)> {
    let Some(source) = key_symbol(code) else {
        return Vec::new();
    };
    // The most specific mapping covering the job's whole scope, as
    // (rank, symbol).
    let mut base: Option<(u8, Option<String>)> = None;
    // Per partial overlap, the most specific mapping there.
    let mut refinements: BTreeMap<Scope, (u8, Option<String>)> = BTreeMap::new();
    for (_, mapping) in maps.iter().filter(|(key, _)| key == code) {
        let Some(scope) = places.scope(&mapping.device, &mapping.app) else {
            continue;
        };
        let Some(overlap) = scope.intersect(job) else {
            continue;
        };
        let symbol = arrives_as(&source, mapping);
        if overlap == *job {
            if base.as_ref().is_none_or(|(rank, _)| scope.rank < *rank) {
                base = Some((scope.rank, symbol));
            }
        } else {
            let entry = refinements.entry(overlap).or_insert((u8::MAX, None));
            if scope.rank < entry.0 {
                *entry = (scope.rank, symbol);
            }
        }
    }
    let base = base.map_or_else(|| Some(source.clone()), |(_, symbol)| symbol);
    let mut sources = vec![(job.clone(), base.clone())];
    // A part where the key arrives as it does in the base rule, or not
    // at all, needs no rule of its own.
    sources.extend(
        refinements
            .into_iter()
            .filter(|(_, (_, symbol))| symbol.is_some() && *symbol != base)
            .map(|(scope, (_, symbol))| (scope, symbol)),
    );
    sources
}

/// The `keymap` blocks for one layer, one per scope.
fn layer_blocks<F: Fn(&str) -> String>(
    layer: &ResolvedLayer<'_>,
    maps: &Maps,
    triggers: &Triggers,
    places: &Places<'_, F>,
) -> Vec<String> {
    // Source symbol → output (`None` emits nothing), per scope.
    let mut rules: BTreeMap<Scope, BTreeMap<String, Option<String>>> = BTreeMap::new();
    for key in &layer.layer.keys {
        // A layer key is remapped before the rules see it, and physical
        // modifiers always pass through: neither can take a job.
        if triggers.contains_key(key.code.as_str()) || is_modifier_key(&key.code) {
            continue;
        }
        let output = match key.action.as_str() {
            "Disabled" => None,
            action => match action_symbol(action) {
                Some(symbol) => Some(symbol),
                None => continue,
            },
        };
        let Some(scope) = places.scope(&key.device, &key.app) else {
            continue;
        };
        for (scope, source) in rule_sources(&key.code, &scope, maps, places) {
            let Some(source) = source else {
                continue;
            };
            rules
                .entry(scope)
                .or_default()
                .entry(source)
                .or_insert_with(|| output.clone());
        }
    }

    let title = format!(
        "Keyloom layer: {}, hold {}",
        layer.layer.name,
        model::key_name(&layer.layer.trigger)
    );
    rules
        .iter()
        .filter(|(_, rules)| !rules.is_empty())
        .map(|(scope, rules)| {
            let mut block = block_header(&title, scope);
            block.push_str("    remap:\n");
            for (source, output) in rules {
                let modifier = layer.modifier;
                match output {
                    Some(key) => block.push_str(&format!("      {modifier}-{source}: {key}\n")),
                    None => block.push_str(&format!("      {modifier}-{source}: []\n")),
                }
            }
            block
        })
        .collect()
}

/// xremap's name for a chord modifier: the alias that matches either
/// key for a side-less one, the key itself for a sided one. Unknown
/// names (the design's "Any") are left out of a chord.
fn modifier_symbol(name: &str) -> Option<&'static str> {
    const KEYS: [[&str; 2]; 4] = [
        ["KEY_LEFTCTRL", "KEY_RIGHTCTRL"],
        ["KEY_LEFTSHIFT", "KEY_RIGHTSHIFT"],
        ["KEY_LEFTALT", "KEY_RIGHTALT"],
        ["KEY_LEFTMETA", "KEY_RIGHTMETA"],
    ];
    let (family, side) = model::parse_modifier(name)?;
    Some(match side {
        ModifierSide::Either => model::MODS[family],
        ModifierSide::Left => KEYS[family][0],
        ModifierSide::Right => KEYS[family][1],
    })
}

/// A chord in xremap's `Mod-Mod-KEY` form, or `None` when its key has
/// no xremap name (an empty chord, or `Hyper`).
fn chord_symbol(chord: &Chord) -> Option<String> {
    let key = action_symbol(&chord.key)?;
    let mut parts: Vec<&str> = chord
        .mods
        .iter()
        .filter_map(|name| modifier_symbol(name))
        .collect();
    parts.push(&key);
    Some(parts.join("-"))
}

/// The `keymap` blocks for the shortcut groups: groups limited to an
/// application first, then the general ones, each in profile order, so
/// a shortcut made for an application wins over the same shortcut made
/// for every application. Paused groups, incomplete rules, and rules
/// with keys xremap cannot name generate nothing. A rule whose two
/// sides are the same changes nothing by itself and is left out, so
/// the key keeps passing through (repeats included); with "any
/// modifier" it still adds the entries that drop a held modifier.
fn group_blocks<F: Fn(&str) -> String>(groups: &[Group], places: &Places<'_, F>) -> Vec<String> {
    let mut blocks: Vec<(u8, String)> = Vec::new();
    for group in groups.iter().filter(|group| group.enabled) {
        let Some(scope) = places.scope("all", &group.scope) else {
            continue;
        };
        let mut lines = String::new();
        // The same chord twice in a group would be a duplicate YAML key.
        let mut seen: Vec<String> = Vec::new();
        let mut rule_line = |from: String, to: &str| {
            if !seen.contains(&from) {
                lines.push_str(&format!("      {from}: {to}\n"));
                seen.push(from);
            }
        };
        for rule in group.rules.iter().filter(|rule| rule.is_complete()) {
            let (Some(from), Some(to)) = (chord_symbol(&rule.from), chord_symbol(&rule.to)) else {
                continue;
            };
            // "Any modifier": the chord also matches with each other
            // modifier held, which xremap then releases around the
            // output instead of passing it through.
            if group.any_mod {
                for (family, modifier) in model::MODS.iter().enumerate() {
                    let held = rule.from.mods.iter().any(|held| {
                        model::parse_modifier(held).is_some_and(|(held, _)| held == family)
                    });
                    if !held {
                        rule_line(format!("{modifier}-{from}"), &to);
                    }
                }
            }
            if from != to {
                rule_line(from, &to);
            }
        }
        if lines.is_empty() {
            continue;
        }
        let mut block = block_header(&format!("Keyloom shortcuts: {}", group.name), &scope);
        block.push_str("    remap:\n");
        block.push_str(&lines);
        blocks.push((scope.rank, block));
    }
    blocks.sort_by_key(|(rank, _)| *rank);
    blocks.into_iter().map(|(_, block)| block).collect()
}

/// Render a profile's mappings, layers, and shortcut groups as a
/// complete xremap document.
///
/// `device_name` resolves a device scope id to the display name xremap
/// should match on. Blocks are written most specific scope first: an
/// application scope's block, then a keyboard's, then the general one
/// (see [`Scope`]).
pub fn generate(rules: Rules<'_>, device_name: impl Fn(&str) -> String) -> String {
    let places = Places {
        apps: rules.apps,
        device_name,
    };
    let layers = resolve_layers(rules.layers);
    let triggers: Triggers = layers
        .iter()
        .map(|layer| (layer.layer.trigger.as_str(), layer.modifier))
        .collect();

    // Group mappings by scope. A mapping whose application scope is
    // gone applies nowhere and is left out.
    let mut scopes: BTreeMap<Scope, Vec<&(String, Mapping)>> = BTreeMap::new();
    for entry in rules.maps {
        let Some(scope) = places.scope(&entry.1.device, &entry.1.app) else {
            continue;
        };
        scopes.entry(scope).or_default().push(entry);
    }
    let mut modmaps: BTreeMap<Scope, BTreeMap<String, Output>> = scopes
        .iter()
        .map(|(scope, mappings)| (scope.clone(), scope_entries(mappings, &triggers)))
        .collect();
    // A layer key produces its modifier everywhere; a mapping of that
    // key in a narrower scope refines it there.
    for layer in &layers {
        modmaps
            .entry(Scope::general())
            .or_default()
            .entry(layer.trigger.clone())
            .or_insert(Output::Key(layer.modifier.to_owned()));
    }

    let mut yaml = format!("{MARKER}\n");
    let blocks: Vec<String> = modmaps
        .iter()
        .filter(|(_, entries)| !entries.is_empty())
        .map(|(scope, entries)| modmap_block(scope, entries))
        .collect();
    if blocks.is_empty() {
        yaml.push_str("modmap: []\n");
    } else {
        yaml.push_str("modmap:\n");
        for block in blocks {
            yaml.push_str(&block);
        }
    }

    if !layers.is_empty() {
        yaml.push_str("virtual_modifiers:\n");
        for layer in &layers {
            yaml.push_str(&format!("  - {}\n", layer.modifier));
        }
    }
    let blocks: Vec<String> = layers
        .iter()
        .flat_map(|layer| layer_blocks(layer, rules.maps, &triggers, &places))
        .chain(group_blocks(rules.groups, &places))
        .collect();
    if !blocks.is_empty() {
        yaml.push_str("keymap:\n");
        for block in blocks {
            yaml.push_str(&block);
        }
    }
    yaml
}

/// Result of writing the generated configuration.
#[derive(Debug, PartialEq, Eq)]
pub enum WriteOutcome {
    /// File created or replaced.
    Written(PathBuf),
    /// File already had exactly this content.
    Unchanged(PathBuf),
    /// An existing file without the Keyloom marker was left untouched.
    SkippedForeign(PathBuf),
}

/// The user's configuration directory: `$XDG_CONFIG_HOME`, or
/// `~/.config` when that is unset.
pub(crate) fn config_home() -> Option<PathBuf> {
    std::env::var_os("XDG_CONFIG_HOME")
        .filter(|dir| !dir.is_empty())
        .map(PathBuf::from)
        .filter(|dir| dir.is_absolute())
        .or_else(|| {
            std::env::var_os("HOME")
                .filter(|home| !home.is_empty())
                .map(|home| PathBuf::from(home).join(".config"))
        })
}

/// Where the generated configuration lives:
/// `$XDG_CONFIG_HOME/xremap/keyloom.yml` (usually `~/.config`).
pub fn config_path() -> Option<PathBuf> {
    Some(config_home()?.join("xremap").join("keyloom.yml"))
}

/// Write the generated document to [`config_path`].
///
/// A pre-existing file that Keyloom did not generate is backed up
/// beside the original before being replaced when `overwrite_foreign`
/// is set, and left untouched otherwise.
pub fn write(yaml: &str, overwrite_foreign: bool) -> io::Result<WriteOutcome> {
    let path = config_path().ok_or_else(|| {
        io::Error::new(io::ErrorKind::NotFound, "no home directory to write into")
    })?;
    write_to(&path, yaml, overwrite_foreign)
}

/// [`write`] with an explicit target path.
pub fn write_to(path: &Path, yaml: &str, overwrite_foreign: bool) -> io::Result<WriteOutcome> {
    if let Ok(existing) = fs::read(path) {
        if existing == yaml.as_bytes() {
            return Ok(WriteOutcome::Unchanged(path.to_owned()));
        }
        if !existing.starts_with(MARKER.as_bytes()) {
            if !overwrite_foreign {
                return Ok(WriteOutcome::SkippedForeign(path.to_owned()));
            }
            backup(path)?;
        }
    }
    let dir = path
        .parent()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "config path has no parent"))?;
    fs::create_dir_all(dir)?;
    // Write-then-rename so a watching xremap never sees a partial file.
    let tmp = path.with_extension("yml.tmp");
    fs::write(&tmp, yaml)?;
    fs::rename(&tmp, path)?;
    Ok(WriteOutcome::Written(path.to_owned()))
}

/// Copy a foreign file to the first free `<name>.bak[.N]` beside it.
pub(crate) fn backup(path: &Path) -> io::Result<()> {
    let file_name = path
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    let mut candidate = path.with_file_name(format!("{file_name}.bak"));
    let mut n = 0u32;
    while candidate.exists() {
        n += 1;
        if n > 999 {
            return Err(io::Error::new(
                io::ErrorKind::AlreadyExists,
                "too many xremap config backups",
            ));
        }
        candidate = path.with_file_name(format!("{file_name}.bak.{n}"));
    }
    fs::copy(path, &candidate)?;
    Ok(())
}

