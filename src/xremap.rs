    #[test]
    fn write_respects_foreign_files_and_backs_them_up() {
        let temp = TempDir::new("write");
        let dir = temp.path();
        let path = dir.join("keyloom.yml");
        let ours = without_layers(&Vec::new());

        // Fresh write, then an identical write is a no-op.
        assert_eq!(
            write_to(&path, &ours, false).unwrap(),
            WriteOutcome::Written(path.clone())
        );
        assert_eq!(
            write_to(&path, &ours, false).unwrap(),
            WriteOutcome::Unchanged(path.clone())
        );

        // A hand-written file is preserved unless overwriting is allowed.
        fs::write(&path, "modmap: [] # hand written\n").unwrap();
        let updated = format!("{ours}# updated\n");
        assert_eq!(
            write_to(&path, &updated, false).unwrap(),
            WriteOutcome::SkippedForeign(path.clone())
        );
        assert_eq!(
            write_to(&path, &updated, true).unwrap(),
            WriteOutcome::Written(path.clone())
        );
        assert_eq!(fs::read_to_string(&path).unwrap(), updated);
        assert_eq!(
            fs::read_to_string(dir.join("keyloom.yml.bak")).unwrap(),
            "modmap: [] # hand written\n"
        );

        // Our own older output is replaced without a backup.
        assert_eq!(
            write_to(&path, &ours, false).unwrap(),
            WriteOutcome::Written(path.clone())
        );
        assert!(!dir.join("keyloom.yml.bak.1").exists());
    }

    /// End-to-end oracle against a real xremap binary: the pinned CLI
    /// loads its configuration *before* selecting devices, so pointing
    /// it at a device name that cannot exist distinguishes "config
    /// parsed" (fails preparing input devices) from "config rejected"
    /// (fails loading the config).
    ///
    /// Ignored during normal local tests to avoid launching the installed
    /// xremap. CI installs the pinned release and explicitly runs this test
    /// with `--ignored`; a missing binary is a failure.
    #[test]
    #[ignore = "launches xremap; CI runs this explicitly with a pinned binary"]
    fn generated_documents_parse_with_real_xremap() {
        use std::process::Command;

        // Every known physical key as a remap source.
        let sources: Vec<&str> = model::registry().map(|cap| cap.code).collect();
        let all_sources: Maps = sources
            .iter()
            .map(|code| map(code, Some("Escape"), None, "all", false))
            .collect();
        // Every translatable catalog action as an output (plus
        // Disabled; Hyper has no key and is dropped by the generator).
        // The catalog holds more actions than there are keys, so cycle
        // sources; one source keeps only its last action, which is fine
        // because every action still appears in some document chunk
        // below.
        let actions: Vec<&&str> = model::ACTION_GROUPS
            .iter()
            .flat_map(|(_, actions)| actions.iter())
            .collect();
        let all_action_chunks: Vec<Maps> = actions
            .chunks(sources.len())
            .map(|chunk| {
                chunk
                    .iter()
                    .enumerate()
                    .map(|(i, action)| map(sources[i], Some(action), None, "all", false))
                    .collect()
            })
            .collect();

        // Every layer modifier in use at once, with every non-modifier
        // key as a job in one layer and every action as a job's output
        // across the others.
        let triggers = ["F1", "F2", "F3", "F4", "F5", "F6", "F7", "F8", "F9", "F10"];
        let job_keys: Vec<&str> = sources
            .iter()
            .copied()
            .filter(|code| !triggers.contains(code) && !is_modifier_key(code))
            .collect();
        let mut all_layers = vec![layer(
            "all-keys",
            triggers[0],
            &job_keys
                .iter()
                .map(|code| (*code, "Escape", "all"))
                .collect::<Vec<_>>(),
        )];
        for (i, chunk) in actions.chunks(job_keys.len()).enumerate() {
            let jobs: Vec<(&str, &str, &str)> = chunk
                .iter()
                .enumerate()
                .map(|(k, action)| (job_keys[k], **action, "all"))
                .collect();
            all_layers.push(layer(&format!("actions-{i}"), triggers[i + 1], &jobs));
        }
        for trigger in &triggers[all_layers.len()..] {
            all_layers.push(layer(trigger, trigger, &[("KeyH", "Arrow Left", "all")]));
        }
        assert_eq!(all_layers.len(), MAX_LAYERS);

        let mut documents = vec![
            ("empty".to_owned(), without_layers(&Vec::new())),
            ("representative".to_owned(), representative()),
            ("all-sources".to_owned(), without_layers(&all_sources)),
            (
                "all-layers".to_owned(),
                generate(&Vec::new(), &all_layers, no_devices),
            ),
        ];
        for (i, chunk) in all_action_chunks.iter().enumerate() {
            documents.push((format!("all-actions-{i}"), without_layers(chunk)));
        }

        let temp = TempDir::new("validate");
        let dir = temp.path();
        for (name, yaml) in &documents {
            let path = dir.join(format!("{name}.yml"));
            fs::write(&path, yaml).unwrap();
            let output = Command::new("xremap")
                .arg("--device")
                .arg("keyloom-validation-no-such-device")
                .arg(&path)
                .output()
                .expect("xremap validation requires the pinned binary on PATH");
            let stderr = String::from_utf8_lossy(&output.stderr);
            assert!(
                !stderr.contains("Failed to load config"),
                "{name}: xremap rejected the generated config:\n{stderr}\n---\n{yaml}"
            );
            assert!(
                stderr.contains("Failed to prepare input devices"),
                "{name}: xremap did not reach device selection:\n{stderr}"
            );
        }
    }
